type Turn struct {
	// Memory and Observability make the agent's services available to custom
	// tools via CurrentTurn. They are excluded from log/JSON representations.
	Memory                    MemoryStore           `json:"-"`
	Observability             ObservabilityProvider `json:"-"`
	UIFeatures                []string
	Metadata                  map[string]any
	User                      User
	ConversationID, RequestID string
}
type turnKey struct{}
type requestIDKey struct{}
type metadataKey struct{}

func RequestMetadata(ctx context.Context) map[string]any {
	m, _ := ctx.Value(metadataKey{}).(map[string]any)
	return m
}

func CurrentTurn(ctx context.Context) (Turn, bool) {
	t, ok := ctx.Value(turnKey{}).(Turn)
	return t, ok
}

type Hooks struct {
	// Name labels telemetry generated by this hook.
	Name string
	// AfterConversation receives a snapshot of the full history for the completed turn.
	// It also runs when the tool-call limit ends the turn, and with auto-save disabled.
	AfterConversation func(context.Context, Turn, Conversation) error
	BeforeMessage     func(context.Context, Turn, string) (string, error)
	AfterMessage      func(context.Context, Turn, Message) error
	BeforeTool        func(context.Context, Turn, Tool, json.RawMessage) (json.RawMessage, error)
	AfterTool         func(context.Context, Turn, Tool, ToolResult) (ToolResult, error)
	// AfterToolResult also runs on validation, access and execution failures.
	// Returning nil retains the current result. Successive hooks see replacements.
	AfterToolResult func(context.Context, Turn, ToolCall, ToolResult) (*ToolResult, error)
}

type Middleware func(context.Context, ModelRequest, func(context.Context, ModelRequest) (Message, error)) (Message, error)

// LLMMiddleware applies callbacks in registration order in each phase. AfterResponse
// receives the request produced by the last BeforeRequest callback.
type LLMMiddleware struct {
	Name          string
	BeforeRequest func(context.Context, ModelRequest) (ModelRequest, error)
	AfterResponse func(context.Context, ModelRequest, Message) (Message, error)
}

type Event struct {
	Usage           *TokenUsage
	Operation, Name string
	Turn            Turn
	Duration        time.Duration
	Err             error
}
type Observer func(context.Context, Event)

func LoggingObserver(log *slog.Logger) Observer {
	return func(ctx context.Context, e Event) {
		log.InfoContext(ctx, "doolla", "operation", e.Operation, "name", e.Name, "user", e.Turn.User.ID, "conversation_id", e.Turn.ConversationID, "request_id", e.Turn.RequestID, "duration", e.Duration, "error", e.Err)
	}
}

// WorkflowDecision can replace the saved messages when a workflow handles a turn.
// A nil Replacement leaves history untouched; an empty slice clears it.
type WorkflowDecision struct {
	Handled     bool
	Replacement []Message
}

// ConversationWorkflow receives a snapshot of the current conversation before the user's message is added.
type ConversationWorkflow func(context.Context, Turn, []Message, string, func(Component) error) (WorkflowDecision, error)

type AgentConfig struct {
	// DefaultLocale applies when the caller does not select a supported locale.
	DefaultLocale string
	Audit         *AuditConfig
	Registry      *ToolRegistry
	HideProgress  bool
	UIFeatures    map[string][]string
	// ReplaceDefaultUIFeatures interprets UIFeatures as the entire policy,
	// matching an explicit Python feature_group_access mapping.
	ReplaceDefaultUIFeatures bool
	WelcomeMessage           string
	SystemPrompt             string
	MaxToolIterations        int
	DisableAutoSave          bool
	StreamResponses          bool
	// VerifyToolAnswers requires current-turn tool receipts for data and memory requests.
	VerifyToolAnswers bool
	// DirectTextRecall opts a service with a custom system prompt or model middleware
	// into returning an authorized, explicitly requested text memory verbatim.
	DirectTextRecall bool
	// DirectSQLResult skips a model summary for an explicitly requested single
	// SELECT once the requested statement has returned a verified scalar result.
	// It requires VerifyToolAnswers and preserves normal tool execution and hooks.
	DirectSQLResult  bool
	Memory           MemoryStore
	TextMemoryRecall MemoryRecall // The zero value uses DefaultTextRecall.
	Conversations    ConversationStore
	Hooks            []Hooks
	Middleware       []Middleware
	LLMMiddlewares   []LLMMiddleware
	Enrichers        []func(context.Context, Turn) (context.Context, error)
	Filters          []func(context.Context, Turn, []Message) ([]Message, error)
	PromptBuilder    func(context.Context, Turn, []ToolSpec) (string, error)
	// EnhanceUserMessages receives the filtered history without the leading
	// system prompt. Its changes apply only to this model request.
	EnhanceUserMessages  func(context.Context, Turn, []Message) ([]Message, error)
	EnhancePrompt        func(context.Context, Turn, string, string) (string, error)
	ConversationWorkflow ConversationWorkflow
	Workflow             func(context.Context, Turn, string, func(Component) error) (bool, error)
	Observe              Observer
	Observability        ObservabilityProvider
	// Recover supplies a delay and permission to retry; the first attempt is 1.
	Recover func(context.Context, Event, int) (time.Duration, bool)
}

func (a *Agent) observe(ctx context.Context, e Event) {
	if recorder, ok := ctx.Value(observeKey{}).(Observer); ok {
		recorder(ctx, e)
	}
	if a.config.Observe != nil {
		a.config.Observe(ctx, e)
	}
}
func (a *Agent) enrich(ctx context.Context, t Turn) (context.Context, error) {
	for _, f := range a.config.Enrichers {
		var err error
		_, trace := a.startSpan(ctx, "agent.context.enrichment", "agent.enrichment.duration", nil, nil)
		ctx, err = f(ctx, t)
		trace.end(err)
		if err != nil {
			return nil, err
		}
	}
	return ctx, nil
}
func (a *Agent) systemPrompt(ctx context.Context, t Turn, q string, tools []ToolSpec) (string, error) {
	prompt := a.config.SystemPrompt
	if a.config.PromptBuilder != nil {
		var err error
		prompt, err = a.config.PromptBuilder(ctx, t, tools)
		if err != nil {
			return "", err
		}
	}
	if a.config.PromptBuilder == nil {
		prompt += "\nToday is " + time.Now().Format("2006-01-02") + ". You are Doolla, a data analyst. Query results are shown directly to the user. Summarize after using the tools."
		for _, spec := range tools {
			switch spec.Name {
			case "search_saved_correct_tool_uses":
				prompt += "\nBefore executing SQL or creating a chart, search for similar successful tool uses with the user's question."
			case "save_question_tool_args":
				prompt += "\nSave successful question and tool argument combinations for future use."
			case "save_text_memory":
				prompt += "\nSave reusable schema or business knowledge as text memory. Exclude temporary query results."
			}
		}
		prompt += "\n" + i18n.T(i18n.WithLocale(ctx, requestedAnswerLocale(q)), "server.model.response_language")
	}
	if a.config.EnhancePrompt != nil {
		child, trace := a.startSpan(ctx, "agent.llm_context.enhance_system_prompt", "agent.llm_context.enhance_system_prompt.duration", nil, nil)
		enhanced, err := a.config.EnhancePrompt(child, t, prompt, q)
		trace.end(err)
		return enhanced, err
	}
	if a.config.Memory != nil {
		found, _ := a.searchTextMemory(ctx, t, q, a.config.TextMemoryRecall.Limit)
		if len(found) > 0 {
			prompt += "\n\n## Relevant Context from Memory\n"
			for _, m := range found {
				prompt += "\n• " + m.Memory.Content
			}
		}
	}
	return prompt, nil
}
func withRecovery[T any](ctx context.Context, a *Agent, e Event, run func() (T, error)) (T, error) {
	for attempt := 1; ; attempt++ {
		if err := ctx.Err(); err != nil {
			var zero T
			return zero, err
		}
		start := time.Now()
		r, err := run()
		if msg, ok := any(r).(Message); ok {
			e.Usage = msg.Usage
		}
		e.Duration = time.Since(start)
		e.Err = err
		a.observe(ctx, e)
		if err == nil || ctx.Err() != nil || a.config.Recover == nil {
			return r, err
		}
		delay, retry := a.config.Recover(ctx, e, attempt)
		if !retry {
			return r, err
		}
		timer := time.NewTimer(delay)
		select {
		case <-timer.C:
		case <-ctx.Done():
			timer.Stop()
			return r, ctx.Err()
		}
	}
}
func (a *Agent) reply(ctx context.Context, t Turn, messages []Message, tools []ToolSpec, focus string) (Message, error) {
	for _, f := range a.config.Filters {
		var err error
		child, trace := a.startSpan(ctx, "agent.conversation.filter", "agent.filter.duration", map[string]any{"message_count_before": len(messages)}, nil)
		messages, err = f(child, t, messages)
		trace.set("message_count_after", len(messages))
		trace.end(err)
		if err != nil {
			return Message{}, err
		}
	}
	if enhance := a.config.EnhanceUserMessages; enhance != nil {
		var prefix []Message
		if len(messages) > 0 && messages[0].Role == "system" {
			prefix, messages = messages[:1:1], messages[1:]
		}
		child, trace := a.startSpan(ctx, "agent.llm_context.enhance_user_messages", "agent.llm_context.enhance_user_messages.duration", map[string]any{"message_count": len(messages)}, nil)
		enhanced, err := enhance(child, t, cloneMessages(messages))
		trace.set("message_count_after", len(enhanced))
		trace.end(err)
		if err != nil {
			return Message{}, err
		}
		messages = append(prefix, enhanced...)
	}
	send := a.sendModel
	if len(a.config.Middleware) > 0 {
		send = func(ctx context.Context, r ModelRequest) (Message, error) {
			return a.sendModel(ctx, r.splitSystem())
		}
		for _, mw := range slices.Backward(a.config.Middleware) {
			next := send
			send = func(c context.Context, r ModelRequest) (Message, error) { return mw(c, r, next) }
		}
	}
	return withRecovery(ctx, a, Event{Operation: "model", Turn: t}, func() (Message, error) {
		request := ModelRequest{Messages: cloneMessages(messages), Tools: tools, User: t.User, Stream: a.config.StreamResponses, Metadata: map[string]any{}}.splitSystem()
		for _, mw := range a.config.LLMMiddlewares {
			if mw.BeforeRequest != nil {
				child, trace := a.middlewareSpan(ctx, mw.Name, "before_llm")
				var err error
				request, err = mw.BeforeRequest(child, request)
				trace.end(err)
				if err != nil {
					return Message{}, err
				}
			}
		}
		outgoing := request
		// Narrow model selection only. Post-response validators still see the
		// authorized tools, including SQL Server's schema inspection middleware.
		if focus != "" {
			outgoing.Tools = slices.DeleteFunc(slices.Clone(request.Tools), func(s ToolSpec) bool { return s.Name != focus })
		}
		if len(a.config.Middleware) != 0 {
			// Preserve the message layout supplied to existing around-call middleware.
			outgoing.Messages, outgoing.SystemPrompt = request.withSystem(), nil
		}
		response, err := send(ctx, outgoing)
		if err != nil {
			return response, err
		}
		for _, mw := range a.config.LLMMiddlewares {
			if mw.AfterResponse != nil {
				child, trace := a.middlewareSpan(ctx, mw.Name, "after_llm")
				response, err = mw.AfterResponse(child, request, response)
				trace.end(err)
				if err != nil {
					return Message{}, err
				}
			}
		}
		return response, nil
	})
}
func (a *Agent) prepareTool(ctx context.Context, t Turn, registered registeredTool, call ToolCall) (json.RawMessage, error) {
	tool := registered.Tool
	args, err := a.registry.prepare(ctx, t.User, registered, json.RawMessage(call.Function.Arguments))
	if err != nil {
		_, trace := a.toolSpan(ctx, call)
		trace.outcome("success", false)
		trace.end(err)
		return nil, err
	}
	for _, h := range a.config.Hooks {
		if h.BeforeTool != nil {
			var err error
			child, trace := a.hookSpan(ctx, h.Name, "before_tool", call.Function.Name)
			args, err = h.BeforeTool(child, t, tool, args)
			trace.end(err)
			if err != nil {
				return nil, err
			}
		}
	}
	return args, nil
}

func (a *Agent) runTool(ctx context.Context, t Turn, tool Tool, call ToolCall, args json.RawMessage) (ToolResult, error) {
	result, err := withRecovery(ctx, a, Event{Operation: "tool", Name: tool.Spec().Name, Turn: t}, func() (ToolResult, error) {
		child, trace := a.toolSpan(ctx, call)
		result, err := a.config.Audit.invoke(child, t, call, args, func() (ToolResult, error) { return tool.Run(child, t.User, args) })
		trace.outcome("success", err == nil && result.Error == "")
		trace.end(err)
		return result, err
	})
	return result, err
}

func (a *Agent) afterToolResult(ctx context.Context, t Turn, call ToolCall, tool Tool, result ToolResult, runSucceeded bool) (ToolResult, error) {
	for _, h := range a.config.Hooks {
		if h.AfterTool != nil && runSucceeded {
			child, trace := a.hookSpan(ctx, h.Name, "after_tool", call.Function.Name)
			var err error
			result, err = h.AfterTool(child, t, tool, result)
			trace.end(err)
			if err != nil {
				// Preserve the original callback's tool-error behavior.
				result = failedToolResult(err)
				break
			}
		}
		if h.AfterToolResult != nil {
			child, trace := a.hookSpan(ctx, h.Name, "after_tool", call.Function.Name)
			replacement, err := h.AfterToolResult(child, t, call, result)
			trace.set("modified_result", replacement != nil)
			trace.end(err)
			if err != nil {
				return ToolResult{}, err
			}
			if replacement != nil {
				result = *replacement
			}
		}
	}
	if result.Error != "" {
		if result.Content == "" {
			result.Content = result.Error
		}
		if !slices.Contains(t.UIFeatures, "tool_error") {
			result.Component = nil
		}
	}
	return result, nil
}

func failedToolResult(err error) ToolResult {
	content := "Tool error: " + err.Error()
	return ToolResult{Error: err.Error(), Content: content, Component: &Component{Type: "notification", Data: map[string]any{"level": "error", "message": content}}}
}

type observeKey struct{}

func WithObserver(ctx context.Context, observer Observer) context.Context {
	return context.WithValue(ctx, observeKey{}, observer)
}

func status(state, message string) Component {
	return Component{Type: "status_bar_update", ID: "doolla-status-bar", Data: map[string]any{"status": state, "message": message}}
}
func uiFeatureGroups(overrides map[string][]string, replaceDefaults bool) map[string][]string {
	groups := make(map[string][]string, len(overrides))
	if !replaceDefaults {
		groups = map[string][]string{
			"tool_names":                      {"admin", "user"},
			"sql_query":                       {"admin", "user"},
			"tool_arguments":                  {"admin"},
			"tool_error":                      {"admin"},
			"tool_invocation_message_in_chat": {"admin"},
			"memory_detailed_results":         {"admin"},
		}
	}
	for name, allowed := range overrides {
		groups[name] = slices.Clone(allowed)
	}
	return groups
}
